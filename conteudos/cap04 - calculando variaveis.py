#Calculando Valores/Variaveis

#Calculando Números (Int ou Float)
num1 = 10
num2 = 20
conta = num1+num2
print(f"{num1} + {num2} = {conta}")

#Calculando Texto (String)
valor1 = "banana"
valor2 = "maçã"
palavra = valor1 + " " + valor2
print(palavra)

