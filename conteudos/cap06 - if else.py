#Estruturas de Condição - If Else
#Permite que certos blocos de códigos sejam executados apenas quando uma condição for verdadeira

#Recebendo e verificando
numero = int(input("Digite um número: "))

#if > condição > ação
if numero == 10:
    print("Você digitou o número 10")

if numero > 5:
    print("Você digitou um número maior que 5")
else:
    print("Você NÃO digitou um número maior que 5")

