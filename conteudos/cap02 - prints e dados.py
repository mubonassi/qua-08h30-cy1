#Print() -> Exibe uma informação DE SAÍDA no terminal

#Tipos de dados

#Texto -> String (Cadeia de Caracteres) -> Necessita de aspas
print("E eu escrevo o que eu quiser aqui dentro")

#Numeros -> A partir dai, não precisa de aspas
#Int -> Integer (Número Inteiro) -> (0,1,2...)
print(56)
#Float (Número Real) -> (0.0,1.0,2.5,3.9,4.1,5.0...)
print(37.5)

#Boolean -> Booleano -> Sim/Não -> Verdadeiro/Falso -> 0/1
print(True)
print(False)

#Lógico -> Função/executa um comando
print(10+20-30*40/50**60)